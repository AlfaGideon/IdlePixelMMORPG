# нормализуем: глифы разной длины (я писал их короче), добиваем нулями до 5x7
FONT: dict[str, list[str]] = {}
for _ch, _bits in _RAW.items():
    _b = _bits.ljust(GLYPH_W * GLYPH_H, ".")
    FONT[_ch] = [_b[i * GLYPH_W:(i + 1) * GLYPH_W] for i in range(GLYPH_H)]


def text_width(text: str, scale: int = 1, tracking: int = 1) -> int:
    if not text:
        return 0
    return (len(text) * GLYPH_W + (len(text) - 1) * tracking) * scale


def draw_text(
    put,
    text: str,
    x: int,
    y: int,
    color,
    scale: int = 1,
    tracking: int = 1,
    shadow=None,
    shadow_offset: int = 1,
) -> int:
    """Рисует текст через callback put(x, y, color). Возвращает ширину."""
    if shadow is not None:
        draw_text(put, text, x + shadow_offset, y + shadow_offset, shadow, scale, tracking)
    cursor = x
    for ch in text.upper():
        glyph = FONT.get(ch)
        if glyph is not None:
            for j, row in enumerate(glyph):
                for i, cell in enumerate(row):
                    if cell != "#":
                        continue
                    for sy in range(scale):
                        for sx in range(scale):
                            put(cursor + i * scale + sx, y + j * scale + sy, color)
        cursor += (GLYPH_W + tracking) * scale
    return cursor - x
